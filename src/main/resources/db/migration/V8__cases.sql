create table case_study (
    id                  bigint generated by default as identity primary key,
    title               varchar(500)  not null,
    country             varchar(100)  not null,
    city                varchar(100),
    customer_name       varchar(300),
    customer_visible    boolean       not null default false,
    summary             varchar(4000),
    challenge           varchar(4000),
    solution            varchar(4000),
    results             varchar(4000),
    deployment_size     varchar(300),
    case_year           int,
    owner_id            bigint        not null,
    publication_allowed boolean       not null default false,
    deleted             boolean       not null default false,
    created_by          varchar(64)   not null,
    created_at          timestamp     not null,
    updated_at          timestamp     not null,
    constraint fk_case_owner foreign key (owner_id) references app_user (id)
);
create index ix_case_country on case_study (country);
create index ix_case_year on case_study (case_year);
create index ix_case_owner on case_study (owner_id);
create index ix_case_deleted on case_study (deleted);

create table case_sku (
    case_id bigint not null,
    sku_id  bigint not null,
    primary key (case_id, sku_id),
    constraint fk_case_sku_case foreign key (case_id) references case_study (id),
    constraint fk_case_sku_sku foreign key (sku_id) references sku (id)
);
create index ix_case_sku_sku on case_sku (sku_id);

create table case_tag (
    case_id bigint not null,
    tag_id  bigint not null,
    primary key (case_id, tag_id),
    constraint fk_case_tag_case foreign key (case_id) references case_study (id),
    constraint fk_case_tag_tag foreign key (tag_id) references tag (id)
);
create index ix_case_tag_tag on case_tag (tag_id);

create table case_artifact (
    case_id     bigint not null,
    artifact_id bigint not null,
    primary key (case_id, artifact_id),
    constraint fk_case_artifact_case foreign key (case_id) references case_study (id),
    constraint fk_case_artifact_artifact foreign key (artifact_id) references artifact (id)
);
create index ix_case_artifact_artifact on case_artifact (artifact_id);
