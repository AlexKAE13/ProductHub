create table question (
    id            bigint generated by default as identity primary key,
    kind          varchar(16)   not null,
    target_type   varchar(16)   not null,
    target_id     bigint        not null,
    author_id     bigint        not null,
    question_text varchar(4000) not null,
    status        varchar(16)   not null,
    answer        varchar(4000),
    answered_by   bigint,
    answered_at   timestamp,
    publish_to_faq boolean      not null default false,
    technical     boolean       not null default false,
    created_at    timestamp     not null,
    updated_at    timestamp     not null,
    constraint fk_question_author foreign key (author_id) references app_user (id),
    constraint fk_question_answered_by foreign key (answered_by) references app_user (id)
);
create index ix_question_target on question (target_type, target_id);
create index ix_question_author on question (author_id);
create index ix_question_status on question (status);
create index ix_question_faq on question (publish_to_faq);

create table task (
    id            bigint generated by default as identity primary key,
    title         varchar(500)  not null,
    description   varchar(4000),
    task_type     varchar(32)   not null,
    status        varchar(16)   not null,
    assignee_id   bigint        not null,
    created_by    varchar(64)   not null,
    due_date      date,
    priority      varchar(8)    not null default 'NORMAL',
    related_type  varchar(16),
    related_id    bigint,
    related_label varchar(300),
    related_url   varchar(300),
    sku_id        bigint,
    source_event  varchar(64),
    created_at    timestamp     not null,
    updated_at    timestamp     not null,
    closed_at     timestamp,
    constraint fk_task_assignee foreign key (assignee_id) references app_user (id),
    constraint fk_task_sku foreign key (sku_id) references sku (id)
);
create index ix_task_assignee_status on task (assignee_id, status);
create index ix_task_related on task (task_type, related_type, related_id, status);
create index ix_task_sku on task (sku_id);
create index ix_task_status on task (status);
create index ix_task_due on task (due_date);
