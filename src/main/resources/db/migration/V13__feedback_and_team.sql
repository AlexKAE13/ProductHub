-- Комментарии к интерфейсу (прямо на страницах) и учетные записи команды отдела.
create table feedback_comment (
    id              bigint generated by default as identity primary key,
    parent_id       bigint,
    page_path       varchar(500)  not null,
    page_query      varchar(500),
    page_title      varchar(300),
    route_pattern   varchar(200),
    view_name       varchar(200),
    selector        varchar(1000),
    element_tag     varchar(40),
    element_text    varchar(500),
    element_html    varchar(1000),
    section_title   varchar(300),
    context_text    varchar(500),
    viewport        varchar(40),
    kind            varchar(16)   not null,
    status          varchar(16)   not null,
    body            varchar(4000) not null,
    resolution_note varchar(1000),
    author_login    varchar(64)   not null,
    author_name     varchar(200)  not null,
    deleted         boolean       not null default false,
    created_at      timestamp     not null,
    updated_at      timestamp     not null,
    constraint fk_feedback_parent foreign key (parent_id) references feedback_comment (id)
);
create index ix_feedback_page on feedback_comment (page_path);
create index ix_feedback_status on feedback_comment (status);
create index ix_feedback_parent on feedback_comment (parent_id);

