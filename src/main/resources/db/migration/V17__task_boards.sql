-- Свои доски задач: название, участники, настраиваемые колонки; архив задач.
-- Задачи без board_id остаются на системной доске "Входящие запросы".
create table task_board (
    id          bigint generated by default as identity primary key,
    name        varchar(120) not null,
    description varchar(500),
    owner_id    bigint       not null,
    created_at  timestamp    not null,
    deleted     boolean      not null default false,
    constraint fk_task_board_owner foreign key (owner_id) references app_user (id)
);

create table task_board_member (
    board_id bigint not null,
    user_id  bigint not null,
    primary key (board_id, user_id),
    constraint fk_task_board_member_board foreign key (board_id) references task_board (id),
    constraint fk_task_board_member_user foreign key (user_id) references app_user (id)
);

create table task_board_column (
    board_id bigint      not null,
    status   varchar(16) not null,
    title    varchar(60) not null,
    color    varchar(16) not null,
    primary key (board_id, status),
    constraint fk_task_board_column_board foreign key (board_id) references task_board (id)
);

alter table task add column board_id bigint;
alter table task add column archived boolean not null default false;
alter table task add column archived_at timestamp;
alter table task add constraint fk_task_board foreign key (board_id) references task_board (id);
create index ix_task_board_archived on task (board_id, archived);
