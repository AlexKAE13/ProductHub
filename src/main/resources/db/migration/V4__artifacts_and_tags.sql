create table tag (
    id       bigint generated by default as identity primary key,
    category varchar(16)   not null,
    tag_value varchar(200) not null,
    value_en varchar(200),
    aliases  varchar(1000),
    active   boolean       not null default true,
    constraint uq_tag_category_value unique (category, tag_value)
);
create index ix_tag_category on tag (category);

create table artifact_type (
    id                 bigint generated by default as identity primary key,
    name               varchar(200) not null,
    importance         int          not null default 3,
    default_contour    varchar(16)  not null default 'INTERNAL',
    producer           varchar(200),
    consumer           varchar(200),
    review_period_days int          not null default 90,
    card_block         varchar(16)  not null default 'DOCS',
    sort_order         int          not null default 0,
    constraint uq_artifact_type_name unique (name)
);

create table artifact (
    id                 bigint generated by default as identity primary key,
    title              varchar(500)  not null,
    description        varchar(4000),
    type_id            bigint        not null,
    language           varchar(8)    not null,
    status             varchar(16)   not null,
    owner_id           bigint        not null,
    contour            varchar(16)   not null default 'INTERNAL',
    current_version_id bigint,
    external_url       varchar(1000),
    line_id            bigint,
    last_reviewed_at   timestamp     not null,
    review_period_days int           not null,
    review_due_at      timestamp     not null,
    source_key         varchar(300),
    deleted            boolean       not null default false,
    created_by         varchar(64)   not null,
    created_at         timestamp     not null,
    updated_at         timestamp     not null,
    constraint fk_artifact_type foreign key (type_id) references artifact_type (id),
    constraint fk_artifact_owner foreign key (owner_id) references app_user (id),
    constraint fk_artifact_line foreign key (line_id) references product_line (id)
);
create index ix_artifact_type on artifact (type_id);
create index ix_artifact_owner on artifact (owner_id);
create index ix_artifact_line on artifact (line_id);
create index ix_artifact_language on artifact (language);
create index ix_artifact_status on artifact (status);
create index ix_artifact_contour on artifact (contour);
create index ix_artifact_review_due on artifact (review_due_at);
create index ix_artifact_updated on artifact (updated_at);
create index ix_artifact_source_key on artifact (source_key);
create index ix_artifact_deleted on artifact (deleted);

create table artifact_version (
    id          bigint generated by default as identity primary key,
    artifact_id bigint       not null,
    version_no  int          not null,
    comment     varchar(1000),
    uploaded_by varchar(64)  not null,
    uploaded_at timestamp    not null,
    constraint uq_artifact_version unique (artifact_id, version_no),
    constraint fk_artifact_version_artifact foreign key (artifact_id) references artifact (id)
);

alter table artifact add constraint fk_artifact_current_version
    foreign key (current_version_id) references artifact_version (id);
create index ix_artifact_current_version on artifact (current_version_id);

create table artifact_file (
    id          bigint generated by default as identity primary key,
    version_id  bigint        not null,
    file_name   varchar(500)  not null,
    stored_path varchar(200)  not null,
    size_bytes  bigint        not null,
    mime_type   varchar(200),
    sha256      varchar(64)   not null,
    role        varchar(16)   not null,
    constraint fk_artifact_file_version foreign key (version_id) references artifact_version (id)
);
create index ix_artifact_file_version on artifact_file (version_id);
create index ix_artifact_file_sha on artifact_file (sha256);

create table artifact_sku (
    artifact_id bigint not null,
    sku_id      bigint not null,
    primary key (artifact_id, sku_id),
    constraint fk_artifact_sku_artifact foreign key (artifact_id) references artifact (id),
    constraint fk_artifact_sku_sku foreign key (sku_id) references sku (id)
);
create index ix_artifact_sku_sku on artifact_sku (sku_id);

create table artifact_tag (
    artifact_id bigint not null,
    tag_id      bigint not null,
    primary key (artifact_id, tag_id),
    constraint fk_artifact_tag_artifact foreign key (artifact_id) references artifact (id),
    constraint fk_artifact_tag_tag foreign key (tag_id) references tag (id)
);
create index ix_artifact_tag_tag on artifact_tag (tag_id);
