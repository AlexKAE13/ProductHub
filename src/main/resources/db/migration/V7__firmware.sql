create table firmware (
    id            bigint generated by default as identity primary key,
    version       varchar(64)    not null,
    release_date  date           not null,
    status        varchar(16)    not null,
    release_notes varchar(20000),
    external_url  varchar(1000),
    file_name     varchar(500),
    stored_path   varchar(200),
    size_bytes    bigint,
    sha256        varchar(64),
    is_public     boolean        not null default false,
    published_by  varchar(64)    not null,
    published_at  timestamp      not null,
    deleted       boolean        not null default false,
    created_at    timestamp      not null,
    updated_at    timestamp      not null
);
create index ix_firmware_status on firmware (status);
create index ix_firmware_release_date on firmware (release_date);
create index ix_firmware_version on firmware (version);
create index ix_firmware_deleted on firmware (deleted);
create index ix_firmware_sha on firmware (sha256);

create table firmware_sku (
    firmware_id bigint not null,
    sku_id      bigint not null,
    primary key (firmware_id, sku_id),
    constraint fk_firmware_sku_firmware foreign key (firmware_id) references firmware (id),
    constraint fk_firmware_sku_sku foreign key (sku_id) references sku (id)
);
create index ix_firmware_sku_sku on firmware_sku (sku_id);
