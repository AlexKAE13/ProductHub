-- Чат (по доске и по карточке) и журнал изменений для своих досок.
create table task_message (
    id         bigint generated by default as identity primary key,
    board_id   bigint        not null,
    task_id    bigint,
    author_id  bigint        not null,
    body       varchar(2000) not null,
    created_at timestamp     not null,
    deleted    boolean       not null default false,
    constraint fk_task_message_board foreign key (board_id) references task_board (id),
    constraint fk_task_message_task foreign key (task_id) references task (id),
    constraint fk_task_message_author foreign key (author_id) references app_user (id)
);
create index ix_task_message_scope on task_message (board_id, task_id, created_at);

create table task_event (
    id         bigint generated by default as identity primary key,
    board_id   bigint       not null,
    task_id    bigint,
    actor_id   bigint       not null,
    kind       varchar(32)  not null,
    subject    varchar(500),
    arg1       varchar(300),
    arg2       varchar(300),
    created_at timestamp    not null,
    constraint fk_task_event_board foreign key (board_id) references task_board (id),
    constraint fk_task_event_task foreign key (task_id) references task (id),
    constraint fk_task_event_actor foreign key (actor_id) references app_user (id)
);
create index ix_task_event_board on task_event (board_id, created_at);
create index ix_task_event_task on task_event (task_id, created_at);
