create table product_line (
    id         bigint generated by default as identity primary key,
    code       varchar(64)  not null,
    name       varchar(200) not null,
    family     varchar(64)  not null,
    owner_id   bigint,
    sort_order int          not null default 0,
    constraint uq_product_line_code unique (code),
    constraint fk_product_line_owner foreign key (owner_id) references app_user (id)
);
create index ix_product_line_family on product_line (family);

create table sku (
    id                     bigint generated by default as identity primary key,
    model                  varchar(200)  not null,
    model_normalized       varchar(200)  not null,
    name_ru                varchar(500),
    name_en                varchar(500),
    line_id                bigint        not null,
    category               varchar(200)  not null,
    site_section_ru        varchar(200),
    site_subsection_ru     varchar(200),
    site_section_en        varchar(200),
    site_subsection_en     varchar(200),
    site_status_ru         varchar(200),
    site_status_en         varchar(200),
    owner_id               bigint        not null,
    chip                   varchar(100),
    lifecycle_status       varchar(32)   not null,
    ga_date                varchar(32),
    eol_announce_date      varchar(32),
    last_order_date        varchar(32),
    last_ship_date         varchar(32),
    end_of_support_date    varchar(32),
    successor_id           bigint,
    last_review_date       date,
    next_review_date       date,
    price                  numeric(14, 2),
    currency               varchar(3),
    price_list             varchar(32),
    availability           varchar(32),
    lead_time_days         int,
    commercial_updated_at  timestamp,
    commercial_updated_by  varchar(64),
    commercial_source      varchar(32),
    description            varchar(10000),
    key_features           varchar(5000),
    plans                  varchar(10000),
    contour                varchar(16)   not null default 'INTERNAL',
    completeness           int           not null default 0,
    deleted                boolean       not null default false,
    created_at             timestamp     not null,
    updated_at             timestamp     not null,
    constraint uq_sku_model unique (model),
    constraint uq_sku_model_normalized unique (model_normalized),
    constraint fk_sku_line foreign key (line_id) references product_line (id),
    constraint fk_sku_owner foreign key (owner_id) references app_user (id),
    constraint fk_sku_successor foreign key (successor_id) references sku (id)
);
create index ix_sku_line on sku (line_id);
create index ix_sku_owner on sku (owner_id);
create index ix_sku_successor on sku (successor_id);
create index ix_sku_category on sku (category);
create index ix_sku_lifecycle on sku (lifecycle_status);
create index ix_sku_next_review on sku (next_review_date);
create index ix_sku_deleted on sku (deleted);

create table spec_definition (
    id                    bigint generated by default as identity primary key,
    spec_key              varchar(64)  not null,
    label_ru              varchar(200) not null,
    label_en              varchar(200) not null,
    unit                  varchar(32),
    value_type            varchar(16)  not null,
    enum_values           varchar(1000),
    group_name            varchar(100) not null,
    applies_to_categories varchar(1000) not null,
    sort_order            int          not null default 0,
    editable_by           varchar(32)  not null,
    constraint uq_spec_definition_key unique (spec_key)
);

create table spec_value (
    id            bigint generated by default as identity primary key,
    sku_id        bigint        not null,
    definition_id bigint        not null,
    spec_value    varchar(1000) not null,
    constraint uq_spec_value unique (sku_id, definition_id),
    constraint fk_spec_value_sku foreign key (sku_id) references sku (id),
    constraint fk_spec_value_definition foreign key (definition_id) references spec_definition (id)
);
create index ix_spec_value_definition on spec_value (definition_id);

create table audit_log (
    id          bigint generated by default as identity primary key,
    entity_type varchar(32)  not null,
    entity_id   bigint       not null,
    action      varchar(32)  not null,
    field       varchar(100),
    old_value   varchar(2000),
    new_value   varchar(2000),
    user_login  varchar(64)  not null,
    note        varchar(200),
    at          timestamp    not null
);
create index ix_audit_entity on audit_log (entity_type, entity_id);

create table import_run (
    id          bigint generated by default as identity primary key,
    kind        varchar(32)  not null,
    started_by  varchar(64)  not null,
    started_at  timestamp    not null,
    finished_at timestamp,
    created     int          not null default 0,
    updated     int          not null default 0,
    skipped     int          not null default 0,
    errors      int          not null default 0,
    log         varchar(20000)
);
