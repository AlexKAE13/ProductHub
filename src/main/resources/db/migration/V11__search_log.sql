-- Журнал поиска (SPEC.md 5.10, 4.10): запросы и клики по результатам.
create table search_log (
    id           bigint generated by default as identity primary key,
    kind         varchar(16)   not null,
    user_login   varchar(64)   not null,
    query_text   varchar(300)  not null,
    result_count bigint,
    took_ms      bigint,
    target_type  varchar(16),
    target_id    bigint,
    at           timestamp     not null
);
create index ix_search_log_at on search_log (at);
create index ix_search_log_kind on search_log (kind);
